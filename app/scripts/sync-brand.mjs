// Copies whatever the brand kit currently ships into the app. Every step is optional:
// the app has inline fallbacks (src/components/Icon.tsx, Mark.tsx, ScrapsFine.tsx),
// so a missing or half-built ../brand/assets never breaks dev or build.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const brandAssets = resolve(root, '../brand/assets')
const publicBrand = join(root, 'public/brand')

rmSync(publicBrand, { recursive: true, force: true })
mkdirSync(publicBrand, { recursive: true })
if (existsSync(brandAssets)) cpSync(brandAssets, publicBrand, { recursive: true })

function svgParts(file) {
  const markup = readFileSync(file, 'utf8')
  const open = markup.match(/<svg[^>]*>/)
  if (!open) return null
  const viewBox = open[0].match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24'
  const inner = markup
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title>[\s\S]*?<\/title>/, '')
  return { viewBox, inner: inner.trim() }
}

// Icons are inlined so they inherit currentColor.
const icons = {}
const iconDir = join(brandAssets, 'icons')
if (existsSync(iconDir)) {
  for (const file of readdirSync(iconDir).filter((name) => name.endsWith('.svg'))) {
    const parts = svgParts(join(iconDir, file))
    if (parts) icons[file.replace('.svg', '')] = parts.inner
  }
}

// Larger single-colour art the app may swap in (falls back to inline drawings when absent).
const art = {}
for (const name of ['scraps-fineline', 'glint']) {
  const file = join(brandAssets, `${name}.svg`)
  if (existsSync(file)) {
    const parts = svgParts(file)
    if (parts) art[name] = parts
  }
}

mkdirSync(join(root, 'src/generated'), { recursive: true })
writeFileSync(
  join(root, 'src/generated/brandIcons.ts'),
  `// GENERATED by scripts/sync-brand.mjs. Do not edit.\nexport const BRAND_ICONS: Record<string, string> = ${JSON.stringify(icons, null, 2)}\n\nexport const BRAND_ART: Record<string, { viewBox: string; inner: string }> = ${JSON.stringify(art, null, 2)}\n`,
)
console.log(
  `sync-brand: ${existsSync(brandAssets) ? 'copied assets' : 'no brand assets yet'}, ${Object.keys(icons).length} icons, ${Object.keys(art).length} art`,
)
